# Writes ../gheg.js from gheg.py so the app and the tests use the same word lists.
import json, os
from gheg import WORDS, PART, IRR, PERSON, MASC_A
HERE = os.path.dirname(os.path.abspath(__file__))
data = {"W": WORDS, "P": PART, "I": IRR, "N": PERSON, "M": sorted(MASC_A)}
js = "// Generated by kaynak/gen_gheg_js.py from gheg.py. Gheg (Kosovo) <-> standard Albanian.\nconst GH = " + json.dumps(data, ensure_ascii=False) + ";\n" + open(os.path.join(HERE, "gheg_fn.js")).read()
open(os.path.join(os.path.dirname(HERE), "gheg.js"), "w").write(js)
print("gheg.js", len(js))
